/// Применяет операцию к каждому элементу массива
fn apply_to_array<F>(arr: &[i32], op: F) -> Vec<i32>
where
    F: Fn(i32) -> i32,
{
    arr.iter().map(|&x| op(x)).collect()
}

/// Изменяет массив на месте
fn apply_in_place<F>(arr: &mut [i32], op: F)
where
    F: Fn(i32) -> i32,
{
    for x in arr.iter_mut() {
        *x = op(*x);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    
    #[test]
    fn test_apply_to_array() {
        let arr = [1, 2, 3, 4, 5];
        let result = apply_to_array(&arr, |x| x * 2);
        assert_eq!(result, vec![2, 4, 6, 8, 10]);
    }
    
    #[test]
    fn test_apply_in_place() {
        let mut arr = [1, 2, 3, 4, 5];
        apply_in_place(&mut arr, |x| x * 2);
        assert_eq!(arr, [2, 4, 6, 8, 10]);
    }
}
